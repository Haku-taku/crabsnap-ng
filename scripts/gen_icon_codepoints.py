#!/usr/bin/env python3
"""Generate the Material Symbols name -> codepoint table for `ui-widgets::icon`.

Material Symbols ships two ways to name an icon: a PUA codepoint in `cmap`, and a
GSUB ligature whose components spell the name. Both land on the same glyph, so the
table is "ligature name -> that glyph's PUA codepoint". PUA is preferred at runtime:
one character, no feature dependency, a fixed one-em advance.

    python3 scripts/gen_icon_codepoints.py \
        '/usr/share/fonts/ttf-material-symbols-variable/MaterialSymbolsOutlined[FILL,GRAD,opsz,wght].ttf' \
        > ui/crates/ui-widgets/src/icon_codepoints.rs

The output is checked in; this script needs fontTools only when regenerating.
"""

import sys
from fontTools.ttLib import TTFont

# Glyph names for the characters that can appear in an icon name.
GLYPH_CHARS = {
    "underscore": "_",
    "hyphen": "-",
    "period": ".",
    "space": " ",
}
for i, word in enumerate(
    ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"]
):
    GLYPH_CHARS[f"digit_{word}"] = str(i)


def char_of(glyph_name: str) -> str | None:
    """The character a component glyph stands for, or None for a non-character glyph."""
    if glyph_name in GLYPH_CHARS:
        return GLYPH_CHARS[glyph_name]
    if len(glyph_name) == 1:
        return glyph_name
    return None


def ligatures(font: TTFont):
    """Yield (name, ligature glyph name) for every GSUB ligature that spells a name."""
    gsub = font["GSUB"].table
    if gsub.LookupList is None:
        return
    for lookup in gsub.LookupList.Lookup:
        for sub in lookup.SubTable:
            # Extension lookups wrap the real subtable one level down.
            if lookup.LookupType == 7:
                sub = sub.ExtSubTable
            # fontTools decompiles ligatures into {first glyph: [Ligature]}; the key is
            # the first component, so the name is key + components.
            for first, ligatures_here in getattr(sub, "ligatures", {}).items():
                for ligature in ligatures_here:
                    parts = []
                    for glyph in [first, *ligature.Component]:
                        ch = char_of(glyph)
                        if ch is None:
                            parts = None
                            break
                        parts.append(ch)
                    if parts:
                        yield "".join(parts), ligature.LigGlyph


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    font = TTFont(sys.argv[1])

    # PUA only: the ASCII entries map to placeholder glyphs, so they are not icon names.
    pua = {}
    for codepoint, glyph in font.getBestCmap().items():
        if 0xE000 <= codepoint <= 0xF8FF:
            pua.setdefault(glyph, codepoint)

    table = {}
    missing = 0
    for name, glyph in ligatures(font):
        codepoint = pua.get(glyph)
        if codepoint is None:
            missing += 1
            continue
        # A renamed icon keeps an old and a new codepoint; the lowest is the stable one.
        table[name] = min(codepoint, table.get(name, codepoint))

    print("//! Generated by `scripts/gen_icon_codepoints.py`; do not edit by hand.")
    print("//! 由 `scripts/gen_icon_codepoints.py` 生成；不要手工编辑。")
    print()
    print("/// Material Symbols icon name -> PUA codepoint, sorted by name.")
    print("/// Material Symbols 图标名 -> PUA 码点，按名字排序。")
    print("pub(crate) const ICONS: &[(&str, char)] = &[")
    for name in sorted(table):
        print(f'    ("{name}", \'\\u{{{table[name]:x}}}\'),')
    print("];")

    print(
        f"generated {len(table)} icons ({missing} ligatures had no PUA codepoint)",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
