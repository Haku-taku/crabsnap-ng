#!/usr/bin/env python3
"""Generate the Fluent icon name -> codepoint table for the Fluent controls.

The vendored `FluentSystemIcons-Regular.ttf` names every glyph `ic_fluent_<name>`,
so the table is the font's cmap with that prefix removed. Nothing is inferred: the
font is the authority, and a name it does not carry is a hard error rather than a
line that silently goes missing.

    python3 scripts/gen_fluent_codepoints.py \
        ui/crates/ui-gallery/assets/fonts/FluentSystemIcons-Regular.ttf \
        > ui/crates/ui-widgets-fluent/src/fluent_codepoints.rs

Only the names the WinUI templates actually ask for are emitted; the font carries
ten thousand, and a checked-in table of all of them would be dead weight. Add a
name here when a control starts using it.
"""

import sys
from fontTools.ttLib import TTFont

PREFIX = "ic_fluent_"

# Every glyph a WinUI template names, plus the ones the WinUI Gallery's pane uses.
# 每个 WinUI 模板会点名的字形，外加 WinUI Gallery 窗格用到的那些。
NAMES = [
    "add_12_regular",
    "add_16_regular",
    "arrow_clockwise_16_regular",
    "arrow_left_16_regular",
    "arrow_sync_16_regular",
    "button_16_regular",
    "checkmark_12_regular",
    "checkmark_16_regular",
    "checkmark_circle_16_regular",
    "checkbox_checked_16_regular",
    "chevron_down_12_regular",
    "chevron_down_16_regular",
    "chevron_left_12_regular",
    "chevron_right_12_regular",
    "chevron_up_12_regular",
    "comment_16_regular",
    "dismiss_12_regular",
    "dismiss_16_regular",
    "document_add_16_regular",
    "error_circle_16_regular",
    "folder_open_16_regular",
    "home_16_regular",
    "important_16_regular",
    "info_16_regular",
    "list_16_regular",
    "navigation_16_regular",
    "options_16_regular",
    "print_16_regular",
    "radio_button_16_regular",
    "save_16_regular",
    "search_16_regular",
    "share_16_regular",
    "subtract_12_regular",
    "tabs_16_regular",
    "text_field_16_regular",
    "toggle_left_16_regular",
    "warning_16_regular",
    "window_16_regular",
]


def main(path: str) -> None:
    font = TTFont(path, lazy=True)
    by_name = {
        name[len(PREFIX):]: codepoint
        for codepoint, name in font.getBestCmap().items()
        if name.startswith(PREFIX)
    }
    missing = [n for n in NAMES if n not in by_name]
    if missing:
        sys.exit("the font does not carry: " + ", ".join(missing))
    print("//! Generated by `scripts/gen_fluent_codepoints.py`; do not edit by hand.")
    print("//! 由 `scripts/gen_fluent_codepoints.py` 生成；不要手工编辑。")
    print()
    print("/// Fluent icon name -> codepoint, sorted by name.")
    print("/// Fluent 图标名 -> 码点，按名字排序。")
    print("pub(crate) const FLUENT_ICONS: &[(&str, char)] = &[")
    for name in sorted(NAMES):
        print(f'    ("{name}", \'\\u{{{by_name[name]:x}}}\'),')
    print("];")


if __name__ == "__main__":
    main(sys.argv[1])
