#!/usr/bin/env python3
"""Generate the SF Symbols name -> codepoint table for `ui-widgets::icon`.

The vendored `SFSymbols.ttf` assigns every symbol a codepoint and names the glyph
after the symbol (`house`, `house_fill`), so the table is just the font's cmap
turned around. Nothing is inferred: the font is the authority.

    python3 scripts/gen_sf_symbol_codepoints.py \
        ui/crates/ui-gallery/assets/fonts/SFSymbols.ttf \
        > ui/crates/ui-widgets/src/sf_symbol_codepoints.rs

The output is checked in; this script needs fontTools only when regenerating.
"""

import sys
from fontTools.ttLib import TTFont


def usable(codepoint: int) -> bool:
    """Whether the codepoint can travel through a text run unchanged.

    Control characters are not drawn and Unicode noncharacters are rejected by some
    shapers, so both are left out rather than shipped as icons that never appear.
    """
    if codepoint < 0x20 or 0xD800 <= codepoint <= 0xDFFF:
        return False
    if 0xFDD0 <= codepoint <= 0xFDEF or (codepoint & 0xFFFE) == 0xFFFE:
        return False
    return True


def main(path: str) -> None:
    font = TTFont(path, lazy=True)
    table = {
        name: codepoint
        for codepoint, name in font.getBestCmap().items()
        if usable(codepoint)
    }
    print("//! Generated by `scripts/gen_sf_symbol_codepoints.py`; do not edit by hand.")
    print("//! 由 `scripts/gen_sf_symbol_codepoints.py` 生成；不要手工编辑。")
    print()
    print("/// SF Symbols icon name -> codepoint, sorted by name.")
    print("/// SF Symbols 图标名 -> 码点，按名字排序。")
    print("pub(crate) const SF_SYMBOLS: &[(&str, char)] = &[")
    for name in sorted(table):
        print(f'    ("{name}", \'\\u{{{table[name]:x}}}\'),')
    print("];")


if __name__ == "__main__":
    main(sys.argv[1])
